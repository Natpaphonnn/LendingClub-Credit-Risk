"""A — fit the competing-risks hazard on 2012-09..2013-12 and evaluate predicted vs actual cumulative default by vintage
(prereg §A). Outputs: data/interim/p2/model_A.pkl; reports/phase2/survival_A.md; reports/figures/p2_A_vintage_ae.png
Usage: nice -n 19 .venv/bin/python -I src/phase2/fit_A.py
"""
import pickle
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src" / "phase1"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from config import FIG, INTERIM  # noqa: E402
from hazard import NAMES, Scaler, cif, coef_table, design, expand, fit_mnl, hazards  # noqa: E402
from metrics import Disc  # noqa: E402
from plotstyle import MUTED, S, plt, save  # noqa: E402

ART2 = INTERIM / "p2"
ART2.mkdir(exist_ok=True)
REP2 = ROOT / "reports" / "phase2"
REP2.mkdir(parents=True, exist_ok=True)
loans = pd.read_parquet(INTERIM / "p2_loans.parquet")
tr = loans[(loans.issue_dt >= "2012-09-01") & (loans.issue_dt <= "2013-12-01")].reset_index(drop=True)
sc = Scaler(tr)
idx, t, y, w = expand(tr)
X = design(t, sc.loan_cols(tr)[idx])
print(f"train loans {len(tr):,}, loan-months {len(t):,}, defaults {int((y==1).sum()):,}, prepays {int((y==2).sum()):,}")
B, cov, its = fit_mnl(X, y, w)
print("converged in", its, "iterations")
with open(ART2 / "model_A.pkl", "wb") as fh:
    pickle.dump({"B": B, "cov": cov, "scaler": sc, "names": NAMES}, fh)
ct = coef_table(B, cov, NAMES)

# ---- predictions by issue quarter (2012Q4 onward)
ev = loans[loans.issue_dt >= "2012-10-01"].reset_index(drop=True)
limit = pd.Timestamp("2018-09-01")
ev["q_last"] = ev.issue_dt.dt.to_period("Q").dt.end_time.dt.to_period("M").dt.to_timestamp()
ev["mob_obs"] = ((limit.year - ev.q_last.dt.year) * 12 + (limit.month - ev.q_last.dt.month)).clip(upper=36)
L = sc.loan_cols(ev)
hd, hp = hazards(L, B)
_, md, C = cif(hd, hp)
naive = 1 - np.prod(1 - hd, axis=1)
ev["pd12"], ev["pd_life"], ev["pd_life_naive"] = C[:, 11], C[:, 35], naive
ev[["pd12", "pd_life", "pd_life_naive"]].assign(issue_q=ev.issue_q).to_parquet(ART2 / "pred_A.parquet")
dmob = ev.default_mob.fillna(999).to_numpy()

rows = []
for q, g in ev.groupby("issue_q"):
    ii = g.index.to_numpy()
    mo = int(g.mob_obs.iloc[0])
    r = {"issue_q": q, "n": len(g), "obs_to_MOB": max(mo, 0), "pred_life_PD": C[ii, 35].mean(),
         "naive_life_PD": naive[ii].mean()}
    for m in (12, 24, 36):
        r[f"pred@{m}"] = C[ii, m - 1].mean()
        r[f"act@{m}"] = (dmob[ii] <= m).mean() if mo >= m else np.nan
    rows.append(r)
Q = pd.DataFrame(rows)
for m in (12, 24, 36):
    Q[f"AE@{m}"] = Q[f"act@{m}"] / Q[f"pred@{m}"]


def period(q):
    y_ = int(q[:4])
    return "train 2012Q4-13" if y_ <= 2013 else "valid 2014" if y_ == 2014 else "OOT 2015" if y_ == 2015 else str(y_)


Q["period"] = Q.issue_q.map(period)
P = []
for per, g in Q.groupby("period", sort=False):
    r = {"period": per, "n": int(g.n.sum())}
    for m in (12, 24, 36):
        h = g[g[f"act@{m}"].notna()]
        r[f"A/E@{m}"] = (h[f"act@{m}"] * h.n).sum() / (h[f"pred@{m}"] * h.n).sum() if len(h) else np.nan
        r[f"quarters@{m}"] = len(h)
    r["pred lifetime PD %"] = 100 * (g.pred_life_PD * g.n).sum() / g.n.sum()
    r["naive lifetime PD %"] = 100 * (g.naive_life_PD * g.n).sum() / g.n.sum()
    P.append(r)
P = pd.DataFrame(P)

# loan-level discrimination of lifetime PD on OOT 2015 (final outcome)
o = ev[(ev.yr == 2015) & ev.bad.notna()]
gini_life = 2 * Disc(o.pd_life.to_numpy(), o.bad.to_numpy()).auc_ks()[0] - 1
gini_m2 = 2 * Disc(o.pd_m2.to_numpy(), o.bad.to_numpy()).auc_ks()[0] - 1
cal = {"OOT mean lifetime PD": o.pd_life.mean(), "OOT final bad rate": o.bad.mean()}

fmt = Q.copy()
for c in [c for c in fmt.columns if c.startswith(("pred", "act", "naive"))]:
    fmt[c] = (100 * fmt[c]).round(2)
for c in [c for c in fmt.columns if c.startswith("AE")]:
    fmt[c] = fmt[c].round(3)
md_ = ["# A — competing-risks lifetime PD (generated by src/phase2/fit_A.py)\n",
       f"Train: {len(tr):,} loans (2012-09..2013-12), {len(t):,} loan-months, {int((y==1).sum()):,} defaults, "
       f"{int((y==2).sum()):,} prepayments; Newton converged in {its} iterations.\n",
       "## Coefficients (multinomial logit vs no-event; int_rate & log amount standardised on train)\n",
       ct.round(4).to_markdown(index=False),
       "\n## A/E of cumulative default by period (n-weighted over quarters observable at that MOB)\n",
       P.round(3).to_markdown(index=False),
       f"\n## Loan-level, OOT 2015 (final outcome)\n\nGini of lifetime PD = {100*gini_life:.1f} (M2 PD alone: {100*gini_m2:.1f}); "
       f"mean lifetime PD {100*cal['OOT mean lifetime PD']:.2f}% vs final bad rate {100*cal['OOT final bad rate']:.2f}%.\n",
       "\n## By issue quarter (%; act = observed unconditional cumulative default; blank = not observable)\n",
       fmt.drop(columns="period").to_markdown(index=False)]
(REP2 / "survival_A.md").write_text("\n".join(md_) + "\n")
print("\n".join(md_[:6]))
print(md_[6])

# figure: A/E at MOB 12 and 24 by quarter
Q = Q[Q["AE@12"].notna()].reset_index(drop=True)
fig, ax = plt.subplots(figsize=(9.5, 3.8))
x = np.arange(len(Q))
ax.plot(x, Q["AE@12"], color=S[0], marker="o", markersize=4, label="A/E at MOB 12")
ax.plot(x, Q["AE@24"], color=S[1], marker="o", markersize=4, label="A/E at MOB 24")
ax.plot(x, Q["AE@36"], color=S[2], marker="o", markersize=4, label="A/E at MOB 36")
ax.axhline(1.0, color=MUTED, linewidth=1, linestyle="--")
ax.set_xticks(x, Q.issue_q, rotation=45, ha="right", fontsize=8)
ax.set_title("Lifetime-PD model (fit 2012-09..2013-12): actual / predicted cumulative default by vintage")
ax.legend(frameon=False, loc="upper left")
save(fig, FIG / "p2_A_vintage_ae.png")
