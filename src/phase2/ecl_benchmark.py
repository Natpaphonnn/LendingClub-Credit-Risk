"""E5 — ECL benchmark (notes/08_prereg_extensions.md §E5): refit at reporting date, LGD discounted at EIR, 90-DPD definition.

Outputs: reports/phase2/ecl_benchmark.md, reports/phase2/ecl_benchmark.json
Usage: nice -n 19 .venv/bin/python -I src/phase2/ecl_benchmark.py
"""
import json
import pickle
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src" / "phase1"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from config import INTERIM  # noqa: E402
from ecl_lib import ecl_from, fit_hazard_asof, fit_on, pooled_lgd, realised_loss, schedule, staging_e4  # noqa: E402
from hazard import hazards  # noqa: E402
from riskutils import as_float, code_events  # noqa: E402

REP2 = ROOT / "reports" / "phase2"
loans = pd.read_parquet(INTERIM / "p2_loans.parquet")
loans["issue_dt"] = pd.to_datetime(loans.issue_dt)
trn = loans[(loans.issue_dt >= "2012-09-01") & (loans.issue_dt <= "2013-12-01")]
port = loans[loans.yr == 2015].reset_index(drop=True)
mA = pickle.load(open(INTERIM / "p2" / "model_A.pkl", "rb"))
dft = trn[trn.loan_status.isin(["Charged Off", "Default"])]

# ---- LGD: undiscounted (reference) and discounted at EIR with recovery timing k
LGD_u, _, _ = pooled_lgd(dft)
LGD_d = {k: pooled_lgd(dft, discount_months=k)[0] for k in (6, 12, 24)}

# ---- models
m_ref = {"B": mA["B"], "scaler": mA["scaler"]}
m_r14 = fit_hazard_asof(loans, "2014-12-31")
m_r15 = fit_hazard_asof(loans, "2015-12-31")
tr90 = trn.copy().reset_index(drop=True)                                       # same complete-outcome window as A
T, ev = code_events(tr90.loan_status.to_numpy(), tr90.lp_mob, as_float(tr90.default_mob) + 2, tr90.W)
tr90["T"], tr90["event"] = T, ev
m_90 = fit_on(tr90)

r, EAD, DF = schedule(port)
real = realised_loss(port)


def run(model, lgd, shift=0):
    hd, hp = hazards(model["scaler"].loan_cols(port), model["B"])
    return ecl_from(hd, hp, EAD, DF, lgd, ead_shift=shift)


scen = {"(a) reference A, undiscounted LGD": (m_ref, 0),
        "(b) reference A, discounted LGD (k=12)": (m_ref, 0),
        "(c) refit at 2014-12-31, discounted LGD (k=12)": (m_r14, 0),
        "(d) 90-DPD default definition, discounted LGD (k=12)": (m_90, 2)}
rows, out = [], {}
for nm, (mdl, sh) in scen.items():
    lgd_ecl = LGD_u if nm.startswith("(a)") else LGD_d[12]
    e = run(mdl, lgd_ecl, sh)
    eu = run(mdl, LGD_u, sh)                                                   # undiscounted LGD for the backtest
    r_ = {"scenario": nm, "mean 12m PD %": 100 * e["pd12"].mean(), "mean lifetime PD %": 100 * e["pdlife"].mean(),
          "day-1 12m ECL $m": e["ecl12"].sum() / 1e6, "lifetime ECL $m": e["ecl_life"].sum() / 1e6}
    if not nm.startswith("(b)"):
        r_["backtest: pred EL (undisc.) $m"] = eu["el_life_undisc"].sum() / 1e6
        r_["realised / predicted"] = real.sum() / eu["el_life_undisc"].sum()
    rows.append(r_)
    out[nm] = r_
T_ = pd.DataFrame(rows)
st = staging_e4(port, m_r15, LGD_d[12], "2015-12-01")
out.update({"LGD_undiscounted": LGD_u, "LGD_discounted": LGD_d, "realised_loss_m": real.sum() / 1e6,
            "refit_2014": {k: v for k, v in m_r14.items() if k in ("n_loans", "defaults", "prepays")},
            "refit_2015": {k: v for k, v in m_r15.items() if k in ("n_loans", "defaults", "prepays")},
            "model_90dpd": {k: v for k, v in m_90.items() if k in ("n_loans", "defaults", "prepays")},
            "staging_refit_2015": st.to_dict(orient="list")})
(REP2 / "ecl_benchmark.json").write_text(json.dumps(out, indent=1, default=float))
Tf = T_.copy()
for c in Tf.columns[1:]:
    Tf[c] = Tf[c].map(lambda v: "" if pd.isna(v) else f"{v:.3f}" if "realised" in c else f"{v:.2f}")
stf = st.copy()
for c in ("gross EAD $m", "allowance $m"):
    stf[c] = stf[c].round(1)
md = f"""# E5 — ECL benchmark for the 2015 portfolio (pre-registered, commit 4562602) — generated by src/phase2/ecl_benchmark.py

LGD (EAD-weighted, {len(dft):,} train-window defaults): undiscounted **{100*LGD_u:.1f}%**; discounted at EIR with recoveries received k months
after default: k = 6 → {100*LGD_d[6]:.1f}%, **k = 12 → {100*LGD_d[12]:.1f}%**, k = 24 → {100*LGD_d[24]:.1f}%.
Refit at 2014-12-31: {m_r14['n_loans']:,} loans (issued 2012-09..2014-12, outcomes observed to 2014-06; {m_r14['defaults']:,} defaults,
{m_r14['prepays']:,} prepayments). Refit at 2015-12-31: {m_r15['n_loans']:,} loans (outcomes to 2015-06). 90-DPD model: same window as A,
default at the 3rd missed instalment ({m_90['defaults']:,} defaults). Realised net principal loss of the 2015 vintage: ${real.sum()/1e6:.1f}m.

## Scenarios

{Tf.to_markdown(index=False)}

Backtest columns use undiscounted LGD ({100*LGD_u:.1f}%) so they compare like-for-like with realised net principal loss.

## Staging at 2015-12-31 under the refit-at-2015-12-31 model and discounted LGD — EX-POST ILLUSTRATION

{stf.to_markdown(index=False)}

Same definitions and caveats as reports/phase2/ecl.md (monthly DPD is not in the data; cured delinquencies are invisible; stage 2 understated).
"""
(REP2 / "ecl_benchmark.md").write_text(md)
print(md)
