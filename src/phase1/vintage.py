"""Vintage analysis (prereg §8): cumulative default rate by MOB, per issue quarter × grade-free risk band
(quintiles of M1 score in train). MOB m shown only when the quarter's last issue month + m <= as-of − 6 months.

Outputs: reports/phase1/vintage.md, reports/figures/p1_vintage_curves.png
Usage: nice -n 19 .venv/bin/python -I src/phase1/vintage.py
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from config import ART, ASOF, CHARGEOFF_LAG_M, FIG, REP, TRAIN, load_base, split_mask  # noqa: E402
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src" / "lib"))
from riskutils import as_float, default_by_mob  # noqa: E402
from plotstyle import SEQ_BLUE, plt, save  # noqa: E402

df = load_base(["issue_dt", "issue_q", "default_mob"])
df = df.join(pd.read_parquet(ART / "scores_m1.parquet", columns=["score_m1"]))
tr = df[split_mask(df, TRAIN)]
# quintile cut points from train (higher score = safer); band 1 = riskiest
cuts = np.quantile(tr.score_m1, [0.2, 0.4, 0.6, 0.8])
df["band"] = 1 + np.searchsorted(cuts, df.score_m1.to_numpy(), side="right")
band_rng = [f"≤{cuts[0]:.0f}"] + [f"{cuts[i]:.0f}–{cuts[i+1]:.0f}" for i in range(3)] + [f">{cuts[3]:.0f}"]
limit = pd.Timestamp(ASOF) - pd.DateOffset(months=CHARGEOFF_LAG_M)
df["q_last"] = df.issue_dt.dt.to_period("Q").dt.end_time.dt.to_period("M").dt.to_timestamp()
mob_max = ((limit.year - df.q_last.dt.year) * 12 + (limit.month - df.q_last.dt.month)).clip(upper=36)
df["mob_obs"] = mob_max


def curves(sub):
    out = {}
    for q, g in sub.groupby("issue_q"):
        mo = int(g.mob_obs.iloc[0])
        if mo < 1:
            continue
        d = np.where(default_by_mob(g.default_mob, 36) > 0, as_float(g.default_mob), 999)
        cnt = np.bincount(np.minimum(d, 37).astype(int), minlength=38)[1:37]
        out[q] = (np.cumsum(cnt) / len(g))[:mo]
    return out


all_c = curves(df)
band_c = {b: curves(df[df.band == b]) for b in range(1, 6)}

# tables at MOB 12 / 24 / 36
qs = sorted(all_c)
rows = []
for q in qs:
    r = {"issue_q": q, "n": int((df.issue_q == q).sum())}
    for m in (12, 24, 36):
        v = all_c[q]
        r[f"all@{m}"] = round(100 * v[m - 1], 2) if len(v) >= m else None
    for b in range(1, 6):
        v = band_c[b].get(q, [])
        r[f"B{b}@12"] = round(100 * v[11], 2) if len(v) >= 12 else None
        r[f"B{b}@24"] = round(100 * v[23], 2) if len(v) >= 24 else None
    rows.append(r)
T = pd.DataFrame(rows)
bsh = df.groupby("issue_q").band.value_counts(normalize=True).unstack().mul(100).round(1)
bsh.columns = [f"%B{c}" for c in bsh.columns]
md = ["# Phase 1 vintage analysis (generated by src/phase1/vintage.py)\n",
      "Cumulative default rate (% of loans originated) by months on book. Default month ≈ last_pymnt_d + 1. "
      f"Risk bands = M1-score quintiles fixed on train (B1 riskiest): {', '.join(f'B{i+1} {r}' for i, r in enumerate(band_rng))}. "
      "2012Q3 = September 2012 only. Empty = not yet observable (needs issue + MOB ≤ 2018-09).\n",
      "## Cumulative default at MOB 12 / 24 / 36 — all bands and by band\n", T.to_markdown(index=False),
      "\n## Band mix by issue quarter (%)\n", bsh.reset_index().to_markdown(index=False)]
(REP / "vintage.md").write_text("\n".join(md) + "\n")
print("\n".join(md))

# figure: 6 panels (all + 5 bands), one thin line per issue quarter, sequential colour by issue year
years = sorted({q[:4] for q in qs})
colmap = dict(zip(years, SEQ_BLUE[-len(years):]))
fig, axes = plt.subplots(2, 3, figsize=(12, 7), sharex=True)
panels = [("All loans", all_c)] + [(f"Band B{b} ({band_rng[b-1]})", band_c[b]) for b in range(1, 6)]
for ax, (title, cs) in zip(axes.ravel(), panels):
    for q, v in cs.items():
        ax.plot(np.arange(1, len(v) + 1), 100 * v, color=colmap[q[:4]], linewidth=1.1)
    ax.set_title(title, fontsize=10)
    ax.set_xticks([6, 12, 18, 24, 30, 36])
for ax in axes[1]:
    ax.set_xlabel("months on book")
for ax in axes[:, 0]:
    ax.set_ylabel("cumulative default, %")
handles = [plt.Line2D([], [], color=colmap[y], linewidth=2, label=y) for y in years]
fig.legend(handles=handles, loc="lower center", ncol=len(years), frameon=False, title="issue year (one line per quarter)")
fig.suptitle("Vintage curves: quarters issued from 2015 on default faster at the same score, in every risk band", x=0.01, ha="left",
             fontweight="bold", color="#0b0b0b")
fig.tight_layout(rect=(0, 0.07, 1, 0.96))
fig.savefig(FIG / "p1_vintage_curves.png", dpi=150)
print("wrote", FIG / "p1_vintage_curves.png")
