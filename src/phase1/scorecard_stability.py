"""Scorecard bin stability (gate round 2, R4-2) — DESCRIPTIVE, not pre-registered.

For each of the scorecard's characteristics and each attribute (bin): population share, bad rate and WoE on train (2012-09..2013-12),
validation (2014) and OOT (2015); bad-rate order reversals between adjacent numeric bins per period; characteristic stability index
(train vs OOT shares). WoE = ln(good share / bad share) with the same +0.5 smoothing as training.
Outputs: reports/phase1/scorecard_stability.md, reports/phase1/scorecard_stability.json
Usage: nice -n 19 .venv/bin/python -I src/phase1/scorecard_stability.py
"""
import json
import pickle
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from config import ART, OOT, REP, TRAIN, VALID, load_base, split_mask  # noqa: E402
from metrics import psi  # noqa: E402

df = load_base()
sc = pickle.load(open(ART / "scorecard.pkl", "rb"))
cols = sc["cols"]
sets = {"train": split_mask(df, TRAIN), "valid 2014": split_mask(df, VALID), "OOT 2015": split_mask(df, OOT)}
rows, summ = [], []
for c in cols:
    b = sc["bins"][c]
    order = list(b.labels)
    per = {}
    for nm, m in sets.items():
        d = df.loc[m & df.bad.notna(), [c, "bad"]]
        lab = b.assign(d[c])
        g = d.groupby(lab.to_numpy(), observed=True).bad.agg(n="size", bad="sum").reindex(order).fillna(0)
        good = g.n - g.bad
        woe = np.log(((good + 0.5) / (good.sum() + 0.5)) / ((g.bad + 0.5) / (g.bad.sum() + 0.5)))
        per[nm] = pd.DataFrame({"share %": 100 * g.n / g.n.sum(), "bad %": 100 * g.bad / g.n.replace(0, np.nan), "WoE": woe})
    for lab_ in order:
        r = {"characteristic": c, "attribute": lab_, "points": sc["points"][c].get(lab_)}
        for nm in sets:
            for k in ("share %", "bad %", "WoE"):
                r[f"{k} {nm}"] = per[nm].loc[lab_, k]
        rows.append(r)
    num = b.kind == "num"
    nonmiss = [x for x in order if x != "MISSING"]
    rev = {}
    for nm in sets:
        br = per[nm].loc[nonmiss, "bad %"].to_numpy()
        tr_dir = np.sign(per["train"].loc[nonmiss, "bad %"].iloc[-1] - per["train"].loc[nonmiss, "bad %"].iloc[0])
        rev[nm] = int(np.sum(np.sign(np.diff(br)) == -tr_dir)) if num and len(br) > 1 else None
    summ.append({"characteristic": c, "kind": b.kind, "attributes": len(order),
                 "bad-rate order reversals train / valid / OOT": "–" if not num else f"{rev['train']} / {rev['valid 2014']} / {rev['OOT 2015']}",
                 "CSI train→OOT": psi(per["train"]["share %"].to_numpy(), per["OOT 2015"]["share %"].to_numpy()),
                 "max |ΔWoE| train→OOT": float((per["OOT 2015"].WoE - per["train"].WoE).abs().max())})
T, S = pd.DataFrame(rows), pd.DataFrame(summ)
(REP / "scorecard_stability.json").write_text(json.dumps({"summary": S.to_dict(orient="list"), "bins": T.to_dict(orient="list")},
                                                          indent=1, default=float))
n_rev = sum(1 for v in S["bad-rate order reversals train / valid / OOT"] if v != "–" and v.split(" / ")[2] != "0")
md = f"""# Scorecard bin stability — DESCRIPTIVE (gate round 2 R4-2; generated by src/phase1/scorecard_stability.py)

Reversal = adjacent non-missing numeric bins whose bad rates move against the training direction. Numeric characteristics with at least one
OOT reversal: **{n_rev} of {int((S.kind == 'num').sum())}**. Reversed bins carry near-identical points (fine bins in flat ranges), so the
effect on scores is small; a future version should merge such bins (minimum bad-rate difference or χ² test) — a spec change, not done here.

## Summary

{S.round(4).to_markdown(index=False)}

## By attribute (share %, bad %, WoE per period)

{T.round(2).to_markdown(index=False)}
"""
(REP / "scorecard_stability.md").write_text(md)
print(md[:2000])
