"""Facts behind tests/test_leakage_and_splits.py, written to reports/quality/leakage_split_proof.md."""
import pickle
import sys
from pathlib import Path

import lightgbm as lgb
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
for p in ("src/phase1", "src/audit"):
    sys.path.insert(0, str(ROOT / p))
from config import ART, BASE, DERIVED, FEATURES, OOT, TRAIN, VALID, split_mask  # noqa: E402
from leakage_map import classify  # noqa: E402

lk = classify()
cls = pd.Series({f: (lk[f][0] if f in lk else "DERIVED") for f in FEATURES}).value_counts()
booster = lgb.Booster(model_file=str(ART / "lgbm.txt"))
sc = pickle.load(open(ART / "scorecard.pkl", "rb"))
banned = sorted(c for c, (k, _) in lk.items() if k in {"LC", "POST", "ID", "TARGET"})
b = pd.read_parquet(BASE, columns=["id", "issue_dt", "bad"])
b["issue_dt"] = pd.to_datetime(b.issue_dt)
rows = []
for nm, w in (("train", TRAIN), ("validation", VALID), ("OOT", OOT)):
    d = b[split_mask(b, w)]
    rows.append({"split": nm, "loans": len(d), "labelled": int(d.bad.notna().sum()), "first issue": d.issue_dt.min().date(),
                 "last issue": d.issue_dt.max().date(), "unique ids": d.id.nunique()})
ids = {r["split"]: set(b[split_mask(b, w)].id) for r, w in zip(rows, (TRAIN, VALID, OOT))}
ov = {f"{a}∩{c}": len(ids[a] & ids[c]) for a, c in (("train", "validation"), ("train", "OOT"), ("validation", "OOT"))}
md = f"""# Leakage and split proof (generated by src/quality/leakage_split_proof.py; asserted in tests/test_leakage_and_splits.py)

## Features reaching application models
- Candidate features: {len(FEATURES)} — classes: {', '.join(f'{k} {v}' for k, v in cls.items())}; derived = {', '.join(DERIVED)}
  (sources: fico_range_low; earliest_cr_line vs issue date; loan_amnt / annual_inc; emp_length — all APP)
- LightGBM model file feature names == candidate list: **{booster.feature_name() == FEATURES}** ({len(booster.feature_name())} features)
- Scorecard characteristics ({len(sc['cols'])}): {', '.join(sc['cols'])} — all in candidate list: **{set(sc['cols']) <= set(FEATURES)}**
- Banned columns (LC / POST / ID / TARGET, {len(banned)}) ∩ features = **{sorted(set(banned) & set(FEATURES)) or 'none'}**
- Lifetime/ECL hazard (not an application model) uses logit(M2 PD), int_rate (LC contract term, documented), log loan_amnt.

## Splits (Phase 1 base, 36m Individual policy-meeting loans)
{pd.DataFrame(rows).to_markdown(index=False)}

Pairwise id overlaps: {ov}. Base ids unique: **{b.id.is_unique}**. Train ends before validation starts and validation ends before OOT starts:
**{rows[0]['last issue'] < rows[1]['first issue'] and rows[1]['last issue'] < rows[2]['first issue']}**.
"""
(ROOT / "reports" / "quality" / "leakage_split_proof.md").write_text(md)
print(md)
